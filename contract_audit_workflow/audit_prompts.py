CONTRACT_TYPE_CLASSIFIER_PROMPT = """你是一个合同类型识别助手。

你的任务是根据输入的合同文本，判断该合同最接近哪一种合同类型。

当前系统支持以下合同类型：
1. 采购合同
2. 服务合同
3. 合作协议
4. 其他

请严格按照以下判断标准进行分类：

【采购合同】
如果合同核心内容是购买、销售、供应、交付货物、设备、物资、商品、材料、软件产品、硬件产品等，且重点条款包含货物名称、规格型号、数量、单价、总价、交货、验收、质保、退换货等内容，则判断为“采购合同”。

常见关键词包括：
采购、供应、货物、商品、设备、物资、材料、订单、交货、收货、验收、质保、退换货、供方、需方、买方、卖方。

【服务合同】
如果合同核心内容是由一方提供服务、咨询、开发、运营、维护、培训、设计、技术支持、人力服务、项目执行等，且重点条款包含服务范围、服务周期、交付成果、验收、人员安排、响应时间、服务费等内容，则判断为“服务合同”。

常见关键词包括：
服务、咨询、技术支持、开发、维护、运营、培训、设计、交付成果、项目实施、服务周期、服务费、服务人员、响应时间、甲方委托乙方。

【合作协议】
如果合同核心内容是双方或多方进行业务合作、市场合作、渠道合作、客户资源共享、商机推荐、联合推广、联合投标、资源互换、收益分配、客户保护、合作框架安排等，则判断为“合作协议”。

常见关键词包括：
合作协议、框架协议、合作框架协议、市场合作协议、市场合作框架协议、战略合作协议、综合合作协议、渠道合作协议、联合推广协议、商务合作协议、客户线索、商机共享、联合拜访、收益分配、资源共享、客户保护、合作期限、退出机制。

【其他】
如果合同文本不属于采购合同、服务合同或合作协议，或合同内容过短、关键信息不足，无法稳定判断，则判断为“其他”。

判断要求：
1. 只能输出以下四个值之一：
采购合同
服务合同
合作协议
其他

2. 不要输出 JSON。
3. 不要输出解释。
4. 不要输出标点符号。
5. 不要输出“合同类型：采购合同”这种格式，只输出类型名称。
6. 不要因为合同中出现“付款”“违约”“争议解决”“保密”“验收”等通用条款就判断合同类型，这些是所有合同都可能出现的内容。
7. 优先根据合同的核心交易内容判断，而不是根据少量关键词判断。
8. 如果同时包含货物采购和安装、调试、售后服务：
   - 以购买货物、设备、材料为主，附带安装、调试或售后服务：输出“采购合同”
   - 以服务交付、项目实施、咨询开发为主，附带少量物料：输出“服务合同”
9. 如果合同标题或正文中出现“合作协议”“框架协议”“市场合作协议”“市场合作框架协议”“战略合作协议”“综合合作协议”“渠道合作协议”“联合推广协议”“商务合作协议”等表述，并且合同核心内容是合作关系、资源共享、客户线索、联合推广、收益分配、合作机制安排，则优先输出“合作协议”。
10. 如果无法判断，请输出“其他”，不要强行归类。

合同文本如下：
{{content}}"""


FINANCE_EXTRA_CRITERIA = """### 财务补充判断标准
审查付款、发票、结算类规则时，不应只看合同是否出现“付款”“发票”等字样，而应判断付款条件、发票开具、验收结果、交付成果之间的关系是否明确。

出现以下情形之一的，不得直接判定为“通过”：
1. 付款仅以签约、提交付款申请、提交交付物、乙方请款等作为条件，但未明确以交付完成、验收合格或收到合规发票作为付款前提；
2. 合同明确排除验收、最终用户验收、系统稳定运行、接口联调完成等作为付款前提；
3. 合同约定先付款后开票，或未明确先开票后付款、发票类型、开票时间、开票主体、税率；
4. 合同约定逾期付款后“另行协商”“友好协商”，但未明确违约金、计算方式或宽限期；
5. 合同对费用构成、费用范围、额外费用审批、阶段付款节点描述不清。"""


LEGAL_EXTRA_CRITERIA = """### 法务补充判断标准
审查法务类规则时，应重点识别“缺失、笼统、另行协商、责任排除、授权不明、权属不明”等风险表达。

出现以下情形之一的，不得直接判定为“通过”：
1. 签署页仅写“授权代表签字”“代表签字”“经办人签字”，但未明确法定代表人身份、授权代表身份或授权依据；
2. 争议解决条款仅写“有管辖权的人民法院”“依法解决”“协商不成可诉讼”，但未明确具体法院、所在地或仲裁机构；
3. 解除后的费用结算、资料返还、账号交接、源代码交付、数据删除、损失赔偿等事项约定为“另行协商”“友好协商”“根据实际情况处理”；
4. 知识产权、源代码所有权、二次开发权、对外销售权、第三方侵权责任等事项约定为“另行协商”或未明确归属；
5. 合同排除或限制乙方对第三方索赔、数据泄露、成果侵权、系统缺陷等责任；
6. 合同涉及系统开发、运维、数据处理、账号配置、接口联调，但未明确数据保密、数据删除、数据返还、备份清理和违规使用责任。"""


PERFORMANCE_EXTRA_CRITERIA = """### 履约补充判断标准
审查履约类规则时，应重点识别履行期限、服务地点、交付物、验收标准、整改机制、变更流程和配合义务是否具体明确。

如果合同使用“合理期限”“及时”“另行确认”“友好协商”“根据实际情况调整”“尽量及时回复”等模糊表述，且未明确具体期限、流程、材料、责任或后果，不得直接判定为“通过”，应结合对应审核规则的默认风险等级输出风险结果。"""


